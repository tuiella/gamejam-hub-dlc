"""One-off generator for the second wave of packs (kept for reference; edit the files in
src/ directly from now on). Writes human-editable sources; run build.py afterwards."""
import io, json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src")


def write(pack, name, text):
    d = os.path.join(ROOT, pack)
    os.makedirs(d, exist_ok=True)
    with io.open(os.path.join(d, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(text.strip("\n") + "\n")


def meta(pack, name, desc):
    write(pack, "pack.json", json.dumps({"id": pack, "name": name, "description": desc, "version": "1.0.0"}, ensure_ascii=False, indent=1))


def sheet(pack, name, hint, csv):
    write(pack, f"{name}.sheet.csv", csv)
    write(pack, f"{name}.sheet.hint", hint)


# ----- diagram helpers -----
def N(i, x, y, text, shape="box", tone="default", w=160, h=56, sub=None):
    n = {"kind": "node", "id": i, "x": x, "y": y, "w": w, "h": h, "shape": shape, "text": text, "tone": tone}
    if sub:
        n["sub"] = sub
    return n


def E(a, b, label=None, dashed=False):
    e = {"id": f"{a}-{b}", "from": a, "to": b}
    if label:
        e["label"] = label
    if dashed:
        e["dashed"] = True
    return e


def G(i, x, y, w, h, title, tone="muted"):
    return {"kind": "group", "id": i, "x": x, "y": y, "w": w, "h": h, "title": title, "tone": tone}


def diagram(pack, name, hint, nodes, edges, groups=()):
    write(pack, f"{name}.diagram.json", json.dumps({"hint": hint, "v": 1, "nodes": nodes, "groups": list(groups), "edges": edges}, ensure_ascii=False, indent=1))


def Z(i, x, y, w, h, title, tone):
    return {"kind": "zone", "id": i, "x": x, "y": y, "w": w, "h": h, "title": title, "tone": tone}


def T(i, x, y, text, tone="amber", w=224, h=88):
    return {"kind": "note", "id": i, "x": x, "y": y, "w": w, "h": h, "text": text, "tone": tone}


def moodboard(pack, name, hint, items):
    write(pack, f"{name}.moodboard.json", json.dumps({"hint": hint, "v": 1, "items": items}, ensure_ascii=False, indent=1))


